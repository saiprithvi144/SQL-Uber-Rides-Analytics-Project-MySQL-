USE uberridesanalyticsdatabase;

-- ============================================================================
#1: Identify the 5 lowest-performing drivers
-- ============================================================================

with ranked as(
SELECT t.driver_id,u.name,round(SUM(p.amount),2) AS total_revenue,DENSE_RANK() OVER (ORDER BY round(SUM(p.amount),2)) as rnk FROM trips t
LEFT JOIN payments p on t.trip_id=p.trip_id
LEFT JOIN drivers d on d.driver_id=t.driver_id
LEFT JOIN users u on u.user_id=d.user_id
where p.status="success"
GROUP BY driver_id
)
select * from ranked where rnk<=5;

-- ============================================================================
#2: Rank riders by Revenue
-- ============================================================================
with ranked as(
SELECT t.rider_id,u.user_id,u.name,round(SUM(t.total_fare),2) AS total_revenue_per_customer,
round(SUM(t.total_fare)*0.2,2) AS revenue_generated_for_uber,
DENSE_RANK() OVER (ORDER BY round(SUM(t.total_fare),2) DESC) as rnk
FROM trips t
LEFT JOIN payments p ON t.trip_id=p.trip_id
LEFT JOIN riders r ON r.rider_id=t.rider_id
LEFT JOIN users u ON u.user_id=r.user_id
WHERE p.status="success"
GROUP BY t.rider_id,u.user_id,u.name
ORDER BY total_revenue_per_customer DESC)
SELECT * FROM ranked WHERE rnk<=5;

-- ============================================================================
#3: Find drivers with the fewest trips
-- ============================================================================

with ranked as(
SELECT t.driver_id, u.name,count(t.trip_id) AS total_trips,
DENSE_RANK() OVER(ORDER BY count(t.trip_id)) AS rnk FROM trips t
JOIN drivers d ON t.driver_id=d.driver_id 
JOIN users u ON d.user_id=u.user_id
GROUP BY t.driver_id,u.name)
SELECT * FROM ranked WHERE rnk<=5;

-- ============================================================================
#4: Find the lowest ranking locations (zone name)
-- ============================================================================
 
 with cte as(
SELECT pickup_location_id as location_id,count(trip_id) AS trip_count_1 FROM trips
GROUP BY pickup_location_id
),
ranked as(
SELECT l.location_id,l.zone_name,cte.trip_count_1 AS total_trips,DENSE_RANK() OVER(ORDER BY cte.trip_count_1) as rnk  FROM locations l
LEFT JOIN cte ON l.location_id=cte.location_id
ORDER BY total_trips
)
SELECT * FROM ranked where rnk<=5;

-- ============================================================================
#5: Find the lowest ranking cities
-- ============================================================================

with cte as(
SELECT pickup_location_id as location_id,count(trip_id) AS trip_count_1 FROM trips
GROUP BY pickup_location_id
),
ranked as(
SELECT l.city,SUM(cte.trip_count_1) AS total_trips,DENSE_RANK() OVER(ORDER BY SUM(cte.trip_count_1)) as rnk  FROM locations l
LEFT JOIN cte ON l.location_id=cte.location_id
GROUP BY l.city
ORDER BY total_trips
)
SELECT * FROM ranked where rnk<=3;

-- ============================================================================
#6: Find the lowest ranking zone types
-- ============================================================================

with cte as(
SELECT pickup_location_id as location_id,count(trip_id) AS trip_count_1 FROM trips
GROUP BY pickup_location_id
),
ranked as(
SELECT l.zone_type,SUM(cte.trip_count_1) AS total_trips,DENSE_RANK() OVER(ORDER BY SUM(cte.trip_count_1)) as rnk  FROM locations l
LEFT JOIN cte ON l.location_id=cte.location_id
GROUP BY l.zone_type
ORDER BY total_trips
)
SELECT * FROM ranked where rnk<=3;

-- ============================================================================
#7: Rank the drivers by their ratings. 
-- ============================================================================
with base as(
SELECT d.driver_id,u.name,round(avg(r.rating),2) AS avg_rating_received FROM drivers d
LEFT JOIN users u ON d.user_id=u.user_id
LEFT JOIN reviews r ON d.user_id=r.reviewee_id
GROUP BY d.driver_id),
ranked as(
SELECT b.*, DENSE_RANK() OVER(ORDER BY b.avg_rating_received DESC) AS rnk
FROM base b )
SELECT * FROM ranked WHERE rnk<=5;

-- ============================================================================
#8: Rank zones along with the city with the lowest total driver count 
-- ============================================================================

SELECT l.location_id,l.zone_name,l.city,
count(DISTINCT t.driver_id) AS unique_driver_count,
count(trip_id) AS location_count,
ROW_NUMBER() OVER(ORDER BY count(DISTINCT t.driver_id),count(trip_id) DESC) AS rnk
FROM trips t
LEFT JOIN locations l ON t.pickup_location_id=l.location_id
GROUP BY l.location_id,l.zone_name,l.city;

-- ============================================================================
#9. Rank the drivers with the highest car breakdowns or vehicle issues
-- ============================================================================

SELECT d.driver_id,u.name,count(cancel_id) AS cancellations FROM trips t
LEFT JOIN cancellations c ON t.trip_id=c.trip_id
LEFT JOIN drivers d ON t.driver_id=d.driver_id
LEFT JOIN users u ON d.user_id=u.user_id
WHERE c.reason="vehicle issue"
GROUP BY d.driver_id,u.name
ORDER BY cancellations DESC;


