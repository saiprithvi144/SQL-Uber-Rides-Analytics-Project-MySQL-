USE uberridesanalyticsdatabase;
-- ============================================================================
-- Drop Existing View
-- ============================================================================

DROP VIEW IF EXISTS report_customer;

-- ============================================================================
-- Create Customer Report View
-- ============================================================================

CREATE VIEW report_customer AS
(
with base as(
SELECT r.rider_id,u.name,u.city,r.rating,u.date_joined AS registered_at FROM riders r
LEFT JOIN users u ON r.user_id=u.user_id
),
base_trip as(
SELECT r.rider_id,r.total_trips, 
min(cast(t.requested_at AS date)) AS first_trip,
max(cast(t.requested_at AS date)) AS last_trip,
count(t.trip_id) AS total_successful_trips,
round(SUM(p.amount),2) AS total_revenue,
round(SUM(p.amount)*0.2,2) AS total_uber_revenue
FROM riders r
LEFT JOIN trips t ON r.rider_id=t.rider_id
LEFT JOIN payments p ON p.trip_id=t.trip_id
WHERE p.status="success"
GROUP BY r.rider_id,r.total_trips
ORDER BY total_revenue DESC),
base_review_g as(
SELECT r.rider_id,r.user_id,
COUNT(re.review_id) AS review_count,
round(avg(re.rating),2) AS avg_review_rating_given 
FROM riders r
LEFT JOIN reviews re ON r.user_id=re.reviewer_id 
GROUP BY r.rider_id,r.user_id
ORDER BY r.rider_id),
base_fail as(
SELECT r.rider_id,
count(t.trip_id) AS total_trips
FROM riders r
LEFT JOIN trips t ON r.rider_id=t.rider_id
GROUP BY r.rider_id
ORDER BY total_trips DESC),
base_review_r as(
SELECT r.rider_id,r.user_id,
COUNT(re.review_id) AS review_count,
round(avg(re.rating),2) AS avg_rating_received 
FROM riders r
LEFT JOIN reviews re ON r.user_id=re.reviewee_id 
GROUP BY r.rider_id,r.user_id
ORDER BY r.rider_id),
base_distance as(
SELECT r.rider_id,round(avg(t.distance_km),2) AS avg_distance_covered FROM riders r 
LEFT JOIN trips t ON t.rider_id=r.rider_id
GROUP BY r.rider_id
)

SELECT 
-- ==========================================================
#Basic customer information
-- ==========================================================

b.*,

-- ==========================================================
#Trip related information and total revenue
-- ==========================================================

f.total_trips,
t.first_trip,t.last_trip,t.total_successful_trips,
f.total_trips-t.total_successful_trips AS total_failed_trips,
di.avg_distance_covered,
t.total_revenue,t.total_uber_revenue,

-- ==========================================================
#Review information and customer segmentation
-- ==========================================================
g.review_count,g.avg_review_rating_given,r.avg_rating_received,
CASE WHEN t.total_successful_trips>=30 AND t.total_revenue>=2000 THEN "VIP"
WHEN t.total_successful_trips>=30 AND t.total_revenue>=1000 THEN "Regular"
ELSE "New"
END AS Rider_Tag

FROM base b
LEFT JOIN base_trip t ON b.rider_id=t.rider_id
LEFT JOIN base_fail f ON b.rider_id=f.rider_id
LEFT JOIN base_review_g g ON b.rider_id=g.rider_id
LEFT JOIN base_review_r r ON b.rider_id=r.rider_id
LEFT JOIN base_distance di ON di.rider_id=b.rider_id
ORDER BY t.total_revenue DESC
)

-- ============================================================================
#End of Script
-- ============================================================================

