USE uberridesanalyticsdatabase;

-- ============================================================================
-- Drop Existing View
-- ============================================================================

DROP VIEW IF EXISTS report_yrmon;

-- ============================================================================
-- Create Customer Report View
-- ============================================================================

CREATE VIEW report_yrmon AS
(
with base_rev as(
SELECT date_format(t.completed_at,"%Y-%m") AS yrmon,
concat("Q",QUARTER(t.completed_at)) AS quarter,
count(t.trip_id) AS total_trips,
#round(sum(p.amount),2) AS total_revenue,
round(sum(p.amount)*0.2,2) AS total_uber_revenue
FROM trips t
LEFT JOIN payments p ON p.trip_id=t.trip_id
WHERE p.status="success"
GROUP BY yrmon,quarter
ORDER BY yrmon),
base_driver as
(SELECT date_format(t.completed_at,"%Y-%m") AS yrmon,
u.name as driver_name,
DENSE_RANK() OVER(PARTITION BY date_format(t.completed_at,"%Y-%m") ORDER BY round(sum(p.amount),2) DESC) AS rnk,
#round(sum(p.amount),2) AS total_revenue,
round(sum(p.amount)*0.2,2) AS total_uber_revenue
FROM trips t
LEFT JOIN payments p ON p.trip_id=t.trip_id
LEFT JOIN drivers d ON t.driver_id=d.driver_id
LEFT JOIN users u ON u.user_id=d.user_id
WHERE p.status="success"
GROUP BY yrmon, t.driver_id
ORDER BY yrmon),
base_city as
(SELECT date_format(t.completed_at,"%Y-%m") AS yrmon,
l.city as city_name,
DENSE_RANK() OVER(PARTITION BY date_format(t.completed_at,"%Y-%m") ORDER BY round(sum(p.amount),2) DESC) AS rnk,
#round(sum(p.amount),2) AS total_revenue,
round(sum(p.amount)*0.2,2) AS total_uber_revenue
FROM trips t
LEFT JOIN payments p ON p.trip_id=t.trip_id
LEFT JOIN locations l ON t.pickup_location_id=l.location_id
WHERE p.status="success"
GROUP BY yrmon, l.city
ORDER BY yrmon),
base_cancel as(
SELECT 
date_format(t.requested_at,"%Y-%m") AS yrmon,
concat("Q",QUARTER(t.requested_at)) AS quarter,
count(t.trip_id) AS total_trips
FROM trips t
WHERE  t.status="cancelled" OR t.status="in_progress"
GROUP BY yrmon,quarter
ORDER BY yrmon)
SELECT b.*,
ca.total_trips AS trips_incomplete,
-- ==========================================================
#Month Over Month Change
-- ==========================================================
#round((b.total_revenue-LAG(b.total_revenue) OVER(ORDER BY b.yrmon)),2) as mom_change,
round((b.total_uber_revenue-LAG(b.total_uber_revenue) OVER(ORDER BY yrmon)),2) as uber_mom_change,
concat(round((((b.total_uber_revenue-LAG(b.total_uber_revenue) OVER(ORDER BY b.yrmon))/(LAG(b.total_uber_revenue) OVER(ORDER BY b.yrmon)))*100),2),"%") as mom_change_pct,

-- ==========================================================
#Cumulative Revenue Percentage
-- ==========================================================
#round((SUM(b.total_revenue) OVER(ORDER BY b.yrmon)),2) AS cumulative_total,
round((SUM(b.total_uber_revenue) OVER(ORDER BY yrmon)),2) AS uber_cumulative_total,
round((round((SUM(b.total_uber_revenue) OVER(ORDER BY b.yrmon)),2)/(SUM(b.total_uber_revenue) OVER())*100),2) AS cumulative_pct,

-- ==========================================================
#Best driver and Highest revenue generated by a city every month, Total trips cancelled or failed.
-- ==========================================================

d.driver_name AS Best_driver,#d.total_revenue AS yrmon_driver_revenue,
d.total_uber_revenue AS yrmon_driver_uber_revenue,
round(((d.total_uber_revenue/b.total_uber_revenue)*100),2) AS yrmon_driver_revenue_pct,
c.city_name AS Best_city,#c.total_revenue AS yrmon_highest_city_revenue, 
c.total_uber_revenue AS yrmon_highest_city_uber_revenue,
round(((c.total_uber_revenue/b.total_uber_revenue)*100),2) AS yrmon_city_revenue_pct
FROM base_rev b
JOIN base_driver d ON b.yrmon=d.yrmon	
JOIN base_city c ON b.yrmon=c.yrmon
JOIN base_cancel ca ON b.yrmon=ca.yrmon
WHERE c.rnk=1 and d.rnk=1
)
-- ============================================================================
#End of Script
-- ============================================================================

